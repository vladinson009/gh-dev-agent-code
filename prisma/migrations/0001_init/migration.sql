CREATE TABLE IF NOT EXISTS developers (
  github_id BIGINT PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  profile JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS repositories (
  github_id BIGINT PRIMARY KEY,
  developer_id BIGINT NOT NULL REFERENCES developers(github_id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  stars INTEGER NOT NULL DEFAULT 0,
  forks INTEGER NOT NULL DEFAULT 0,
  language TEXT,
  updated_at TIMESTAMPTZ NOT NULL,
  repository JSONB NOT NULL
);

CREATE INDEX IF NOT EXISTS repositories_developer_stars_idx
  ON repositories(developer_id, stars DESC);

CREATE TABLE IF NOT EXISTS api_cache (
  cache_key TEXT PRIMARY KEY,
  payload JSONB NOT NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS api_cache_expires_at_idx ON api_cache(expires_at);

CREATE TABLE IF NOT EXISTS developer_snapshots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  developer_id BIGINT NOT NULL REFERENCES developers(github_id) ON DELETE CASCADE,
  followers INTEGER NOT NULL,
  public_repos INTEGER NOT NULL,
  total_stars BIGINT NOT NULL,
  total_forks BIGINT NOT NULL,
  captured_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS developer_snapshots_history_idx
  ON developer_snapshots(developer_id, captured_at DESC);

CREATE TABLE IF NOT EXISTS repository_snapshots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  repository_id BIGINT NOT NULL REFERENCES repositories(github_id) ON DELETE CASCADE,
  stars INTEGER NOT NULL,
  forks INTEGER NOT NULL,
  captured_at TIMESTAMPTZ NOT NULL,
  UNIQUE (repository_id, captured_at)
);

CREATE INDEX IF NOT EXISTS repository_snapshots_history_idx
  ON repository_snapshots(repository_id, captured_at DESC);

CREATE TABLE IF NOT EXISTS users (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  github_id BIGINT NOT NULL UNIQUE,
  username TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS watchlists (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (user_id, name)
);

CREATE TABLE IF NOT EXISTS watchlist_items (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  watchlist_id UUID NOT NULL REFERENCES watchlists(id) ON DELETE CASCADE,
  resource_type TEXT NOT NULL CHECK (resource_type IN ('developer', 'repository')),
  developer_id BIGINT REFERENCES developers(github_id) ON DELETE CASCADE,
  repository_id BIGINT REFERENCES repositories(github_id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (
    (resource_type = 'developer' AND developer_id IS NOT NULL AND repository_id IS NULL)
    OR
    (resource_type = 'repository' AND repository_id IS NOT NULL AND developer_id IS NULL)
  ),
  UNIQUE (watchlist_id, developer_id),
  UNIQUE (watchlist_id, repository_id)
);
